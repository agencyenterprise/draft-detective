"""What Reviewer 2 is judged on.

The workflow writes two prose documents, a peer review in four sections and a
devil's-advocate rebuttal, so there is no issue inventory to match. Instead
each record names the substantive weaknesses planted in the document and its
genuine strengths, and a judge grades each point on its own: whether the
review raises each weakness, credits each strength, and does not attack a
strength as a flaw (the persona's likely failure on a sound paper). Three
further criteria are graded once per sample: everything the review says the
document says or lacks is accurate, the next steps are concrete and specific,
and the rebuttal argues against the paper and ends by conceding where it is
weakest.

Deterministic checks read the documents' shape against the skill: both were
produced; the review has its four sections; Section 4 lists five to seven
recommendations; and both header blocks carry the reviewer name, the AI
disclaimer, the document's title and its authors' names.
"""

import math
import re
from typing import Optional, Sequence

from inspect_ai.scorer._model import default_instructions  # type: ignore[attr-defined]
from pydantic import BaseModel, ConfigDict, Field

from evals_inspectai.common.issue_inventory import normalize

# Characters each document must reach to count as produced.
MIN_CHARS = 200
# Lines at the top of a document that make up its header block.
HEADER_LINES = 25
NEXT_STEPS_RANGE = (5, 7)

# Whole words, so a recommendation headed "Strengthen the design" does not read as Section 2.
SECTIONS = {
    "summary": re.compile(r"\bsummary\b", re.I),
    "strengths": re.compile(r"\bstrengths?\b", re.I),
    "weaknesses": re.compile(r"\bweakness(?:es)?\b", re.I),
    "next_steps": re.compile(r"\bnext steps\b|\bactionable\b|\brecommendations\b", re.I),
}
# The level a wholly bold line counts as, next to markdown's 1 to 6: a section title.
_BOLD_LEVEL = 2
_HEADING_RE = re.compile(r"^\s*(?:#{1,6}\s+(?P<md>.+?)|\*\*(?P<bold>[^*]+)\*\*:?)\s*$")
_TABLE_ROW_RE = re.compile(r"^\s*\|.*\|\s*$")
_SEPARATOR_RE = re.compile(r"^\s*\|?[\s:|-]+\|?\s*$")
_REVIEWER_RE = re.compile(r"draft detective\s*[—–-]+\s*reviewer 2", re.I)
# The note the skill requires, word for word; compared after normalising case, quotes,
# whitespace and markdown emphasis.
DISCLAIMER = (
    "This review was generated by an AI system and is intended as a starting point for evaluation. It should be "
    "critically assessed by human reviewers before being used to inform editorial or research decisions."
)
_TITLE_RE = re.compile(r"^#\s+(.+?)\s*$", re.M)


class Point(BaseModel):
    model_config = ConfigDict(extra="forbid")

    id: str
    point: str = Field(description="The weakness or strength, stated as a reviewer would")


class Reviewer2Record(BaseModel):
    model_config = ConfigDict(extra="forbid")

    input: str = Field(description="The document: inline markdown, or file://<path> relative to evals_inspectai/")
    weaknesses: list[Point] = Field(description="Substantive weaknesses a rigorous review raises")
    strengths: list[Point] = Field(default_factory=list, description="Genuine strengths the review credits and does not attack")
    authors: list[str] = Field(default_factory=list, description="Surnames both header blocks must name; empty when the document names none")
    notes: Optional[str] = None


class Reviewer2Output(BaseModel):
    """Local mirror of Reviewer2State's markdown outputs."""

    peer_review_markdown: Optional[str] = None
    rebuttal_markdown: Optional[str] = None


def headings(markdown: str) -> list[tuple[int, int, str]]:
    """The 0-indexed line, level and text of each heading: a markdown heading, or a line
    that is wholly bold (the skill's "SECTION 1: ..." is often written that way)."""
    found = []
    for number, line in enumerate(markdown.split("\n")):
        match = _HEADING_RE.match(line)
        if match:
            level = len(line.lstrip()) - len(line.lstrip().lstrip("#")) if match.group("md") else _BOLD_LEVEL
            found.append((number, level, (match.group("md") or match.group("bold") or "").strip()))
    return found


def section_starts(markdown: str) -> dict[str, tuple[int, int]]:
    """The line and level of each required section's heading: the largest set of sections
    whose headings come in the skill's order, each heading heading one section at most, so a
    composite heading ("Summary, Strengths and Weaknesses") cannot stand in for several and
    a later heading that mentions a summary cannot displace Section 1. Among assignments of
    the same size, each section takes its earliest heading. A section left without a heading
    is left out."""
    marks = headings(markdown)
    keys = list(SECTIONS)
    matches = [[SECTIONS[k].search(text) is not None for k in keys] for _, _, text in marks]
    # best[i][k]: most sections k.. that headings i.. can head in order.
    best = [[0] * (len(keys) + 1) for _ in range(len(marks) + 1)]
    for i in range(len(marks) - 1, -1, -1):
        for k in range(len(keys) - 1, -1, -1):
            take = 1 + best[i + 1][k + 1] if matches[i][k] else 0
            best[i][k] = max(take, best[i + 1][k], best[i][k + 1])
    starts: dict[str, tuple[int, int]] = {}
    i = k = 0
    while i < len(marks) and k < len(keys):
        if matches[i][k] and best[i][k] == 1 + best[i + 1][k + 1]:
            starts[keys[k]] = (marks[i][0], marks[i][1])
            i, k = i + 1, k + 1
        elif best[i][k] == best[i + 1][k]:
            i += 1
        else:
            k += 1
    return starts


def _section(markdown: str, key: str) -> Optional[str]:
    """The text under the section's heading (see ``section_starts``), up to the next heading
    at the same or a higher level (a recommendation's own subheading does not end Section
    4); None when the section has no heading."""
    start = section_starts(markdown).get(key)
    if start is None:
        return None
    lines = markdown.split("\n")
    line, level = start
    ends = [n for n, other, _ in headings(markdown) if n > line and other <= level]
    return "\n".join(lines[line + 1 : ends[0] if ends else len(lines)])


def _tables(markdown: str) -> list[list[str]]:
    """Each markdown table's rows, separator rows left out; any other line ends a table."""
    tables: list[list[str]] = []
    current: list[str] = []
    for line in markdown.split("\n") + [""]:
        if _TABLE_ROW_RE.match(line):
            if not _SEPARATOR_RE.match(line):
                current.append(line)
        elif current:
            tables.append(current)
            current = []
    return tables


def _first_cell(row: str) -> str:
    return row.strip().strip("|").split("|")[0]


def recommendation_count(section: str) -> int:
    """How many recommendations Section 4 lists: the table rows whose first cell names the
    core issue when there are any (one per recommendation, however the tables are laid
    out), otherwise the number of tables when there are several (one table each),
    otherwise the data rows of the one table."""
    tables = _tables(section)
    core = [row for table in tables for row in table if re.search(r"core issue", _first_cell(row), re.I)]
    if core:
        return len(core)
    if len(tables) > 1:
        return len(tables)
    return max(len(tables[0]) - 1, 0) if tables else 0


def _header(markdown: str) -> str:
    """The header block's text, normalised, with markdown emphasis and quote markers removed."""
    return normalize(re.sub(r"[*_>]", " ", "\n".join(markdown.split("\n")[:HEADER_LINES])))


def header_checks(markdown: str, title: str, authors: Sequence[str]) -> list[tuple[str, bool]]:
    header = _header(markdown)
    checks = [
        ("reviewer name", _REVIEWER_RE.search(header) is not None),
        ("AI disclaimer", normalize(DISCLAIMER) in header),
        ("document title", bool(title) and normalize(title) in header),
    ]
    checks += [(f"author {a}", normalize(a) in header) for a in authors]
    return checks


def document_title(document: str) -> str:
    match = _TITLE_RE.search(document)
    return match.group(1) if match else ""


def structure_scores(output: Reviewer2Output, document: str, authors: Sequence[str]) -> tuple[dict[str, float], str]:
    """``both_produced``: 1 when both documents reach ``MIN_CHARS``. ``review_sections``:
    share of the four sections the review heads, each under its own heading and in order. ``next_steps_in_range``: 1 when Section 4
    lists five to seven recommendations (0 when it is missing). ``header_block``: share of the
    header elements (reviewer name, disclaimer, title, each author) present at the top of
    both documents. The last three are NaN when the review was not produced."""
    review = (output.peer_review_markdown or "").strip()
    rebuttal = (output.rebuttal_markdown or "").strip()
    produced = len(review) >= MIN_CHARS and len(rebuttal) >= MIN_CHARS
    if len(review) < MIN_CHARS:
        nan = {"review_sections": math.nan, "next_steps_in_range": math.nan, "header_block": math.nan}
        return {"both_produced": float(produced), **nan}, f"peer review missing or too short ({len(review)} chars)"
    missing = [k for k in SECTIONS if k not in section_starts(review)]
    steps = _section(review, "next_steps")
    count = recommendation_count(steps) if steps is not None else 0
    low, high = NEXT_STEPS_RANGE
    title = document_title(document)
    checks = [(f"review {name}", ok) for name, ok in header_checks(review, title, authors)]
    # A missing rebuttal fails its header checks too; both_produced records that it is missing.
    checks += [(f"rebuttal {name}", ok) for name, ok in header_checks(rebuttal, title, authors)]
    values = {
        "both_produced": float(produced),
        "review_sections": 1 - len(missing) / len(SECTIONS),
        "next_steps_in_range": float(low <= count <= high),
        "header_block": sum(ok for _, ok in checks) / len(checks),
    }
    notes = [] if produced else [f"rebuttal missing or too short ({len(rebuttal)} chars)"]
    notes += [f"sections missing: {missing}"] if missing else []
    notes += [f"{count} recommendations in Section 4"] if not low <= count <= high else []
    notes += [f"header lacks: {[n for n, ok in checks if not ok]}"] if not all(ok for _, ok in checks) else []
    return values, " | ".join(notes) if notes else "structure as the skill asks"


REVIEW_TEMPLATE = """You are grading an AI-written review of a research document against one criterion.

[BEGIN DATA]
************
[Document under review]: {document}
************
[{output_label}]: {output}
************
{point_block}[Criterion]: {criterion}
************
[END DATA]

{instructions}
"""


def review_prompt(criterion: str, document: str, output_label: str, output: str, point: Optional[str] = None) -> str:
    return REVIEW_TEMPLATE.format(
        document=document,
        output_label=output_label,
        output=output,
        point_block=f"[Point]: {point}\n************\n" if point else "",
        criterion=criterion,
        instructions=default_instructions(partial_credit=True),
    )


