"""The Reviewer 2 eval: its dataset, its structure checks, and the judged loop with a scripted grader."""

import math
from pathlib import Path
from typing import cast

import pytest
import yaml
from inspect_ai.model import Model

from evals_inspectai.e2e.reviewer_2.criteria import (
    JUDGED_KEYS,
    Point,
    Reviewer2Output,
    Reviewer2Record,
    recommendation_count,
    structure_scores,
)
from evals_inspectai.e2e.reviewer_2.reviewer_2_e2e import judge_review, reviewer_2_e2e

DATASET = Path("evals_inspectai/e2e/reviewer_2/dataset.yaml")
DOC = "# Remote Work and Happiness\n\n**Authors:** Elena Marsh and Kofi Mensah\n\nRemote workers are happier.\n"
HEADER = (
    "# Peer Review: Remote Work and Happiness\n\n**Authors:** Elena Marsh, Kofi Mensah\n"
    "**Reviewer:** Draft Detective — Reviewer 2\n\n*This review was generated by an AI system and is intended as a starting point.*\n\n"
)
TABLE = "| | |\n|---|---|\n| **Core issue** | Selection |\n| **Steps** | Control for occupation |\n| **Tradeoffs** | Needs data |\n\n"
REVIEW = (
    HEADER
    + "## Section 1: Summary of Argument\n\nThe paper argues remote work makes workers happier. " + "x" * 200 + "\n\n"
    + "## Section 2: Strengths\n\nThe question wording is given.\n\n"
    + "## Section 3: Weaknesses\n\nThe panel is opt-in.\n\n"
    + "## Section 4: Actionable Next Steps\n\n" + TABLE * 5
    + "Future research could track workers over time.\n"
)
REBUTTAL = HEADER + "## Rebuttal\n\n" + "The case against the paper. " * 20 + "\n\n## Where this rebuttal is weakest\n\nThe interval is tight.\n"
RECORD = Reviewer2Record(
    input=DOC,
    weaknesses=[Point(id="panel", point="Opt-in panel."), Point(id="selection", point="Selection into remote work.")],
    strengths=[Point(id="wording", point="Question wording given.")],
    authors=["Marsh", "Mensah"],
)


class _Completion:
    def __init__(self, completion: str) -> None:
        self.completion = completion


class _Grader:
    """Answers I for prompts mentioning ``fail_on``, C otherwise, and keeps the prompts."""

    def __init__(self, fail_on: str = "\x00") -> None:
        self.fail_on = fail_on
        self.prompts: list[str] = []

    async def generate(self, prompt: str) -> _Completion:
        self.prompts.append(prompt)
        return _Completion("GRADE: I" if self.fail_on in prompt else "GRADE: C")


def test_dataset_is_well_formed():
    raw = yaml.safe_load(DATASET.read_text())
    records = [Reviewer2Record.model_validate(r) for r in raw]
    assert len(records) == 12
    assert all(r.weaknesses for r in records)
    assert sum(len(r.weaknesses) for r in records) == 45 and sum(len(r.strengths) for r in records) == 21
    for r in records:
        ids = [p.id for p in r.weaknesses + r.strengths]
        assert len(ids) == len(set(ids)), "point ids are unique within a record"
        assert all(a in r.input for a in r.authors), "every named author is in the document"


def test_task_has_the_structure_and_judged_scorers():
    t = reviewer_2_e2e()
    assert len(t.dataset) == 12 and len(t.scorer) == 2
    assert set(t.metadata["metrics"]["review_judged"]) == set(JUDGED_KEYS)


def test_a_review_with_the_skills_structure_passes_every_structure_check():
    values, note = structure_scores(Reviewer2Output(peer_review_markdown=REVIEW, rebuttal_markdown=REBUTTAL), DOC, RECORD.authors)
    assert values == {"both_produced": 1.0, "review_sections": 1.0, "next_steps_in_range": 1.0, "header_block": 1.0}, note


def test_structure_checks_name_what_is_missing():
    review = REVIEW.replace("## Section 2: Strengths", "## Section 2: What Works").replace(TABLE * 5, TABLE * 3)
    rebuttal = REBUTTAL.replace("Draft Detective — Reviewer 2", "Anonymous")
    values, note = structure_scores(Reviewer2Output(peer_review_markdown=review, rebuttal_markdown=rebuttal), DOC, RECORD.authors)
    assert values["review_sections"] == 0.75 and values["next_steps_in_range"] == 0.0
    assert values["header_block"] == 9 / 10
    assert "strengths" in note and "3 recommendations" in note and "rebuttal reviewer name" in note


def test_a_recommendation_subheading_does_not_end_the_next_steps_section():
    """"Strengthen" is not the Strengths section, and a deeper heading is not a section boundary."""
    steps = "".join(f"### {i}. Strengthen the design\n\n{TABLE}" for i in range(1, 7))
    review = REVIEW.replace(TABLE * 5, steps)
    values, note = structure_scores(Reviewer2Output(peer_review_markdown=review, rebuttal_markdown=REBUTTAL), DOC, RECORD.authors)
    assert values["next_steps_in_range"] == 1.0, note


def test_structure_checks_are_nan_without_a_review():
    values, _ = structure_scores(Reviewer2Output(rebuttal_markdown=REBUTTAL), DOC, RECORD.authors)
    assert values["both_produced"] == 0.0
    assert all(math.isnan(values[k]) for k in ("review_sections", "next_steps_in_range", "header_block"))


def test_recommendations_are_counted_however_the_tables_are_laid_out():
    one_table = "| Issue | Steps | Tradeoffs |\n|---|---|---|\n" + "| a | b | c |\n" * 6
    untitled = ("| a | b |\n|---|---|\n| c | d |\n\n") * 7
    assert recommendation_count(TABLE * 6) == 6
    assert recommendation_count(one_table) == 6
    assert recommendation_count(untitled) == 7
    assert recommendation_count("No tables at all.") == 0


@pytest.mark.asyncio
async def test_each_planted_point_is_graded_on_its_own():
    grader = _Grader(fail_on="[Point]: Selection into remote work.")
    output = Reviewer2Output(peer_review_markdown=REVIEW, rebuttal_markdown=REBUTTAL)
    values, note = await judge_review(cast(Model, grader), DOC, output, RECORD, calls=1)
    assert values["weaknesses_raised"] == 0.5
    assert values["strengths_credited"] == 1.0 and values["strengths_not_attacked"] == 1.0
    assert values["claims_accurate"] == values["next_steps_concrete"] == values["rebuttal_concedes"] == 1.0
    assert len(grader.prompts) == 2 + 1 + 1 + 3
    assert all(f"[Document under review]: {DOC}" in p for p in grader.prompts)
    assert sum("[Rebuttal]:" in p for p in grader.prompts) == 1
    assert note == "weaknesses_raised: selection 0.0"


@pytest.mark.asyncio
async def test_a_missing_rebuttal_fails_its_criterion_and_no_strengths_leave_theirs_unscored():
    grader = _Grader()
    record = RECORD.model_copy(update={"strengths": []})
    values, _ = await judge_review(cast(Model, grader), DOC, Reviewer2Output(peer_review_markdown=REVIEW), record, calls=1)
    assert values["rebuttal_concedes"] == 0.0
    assert math.isnan(values["strengths_credited"]) and math.isnan(values["strengths_not_attacked"])
